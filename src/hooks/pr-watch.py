def main(argv: list[str]) -> int:
    if os.environ.get("PR_WATCH") == "0":
        return 0
    harness, event = parse_arguments(argv)
    hook_input = read_input()
    if event == "Stop":
        if hook_input.get("stop_hook_active") is True or hook_input.get("continuation_active") is True:
            return 0
        reason = hook_input.get("terminationReason")
        if reason and reason != "NO_TOOL_CALL":
            return 0

    cwd = workspace_dir(hook_input)
    host, branch_target, explicit = watch_targets(cwd)
    path = state_path(session_key(hook_input))
    state = load_state(path)
    # A pull request watched earlier is still checked when the checkout has
    # moved on (detached HEAD or another branch after a merge).
    if not branch_target and not with_watched(state, host, explicit):
        return 0
    if event == "Rewake":
        return rewake(path, host, branch_target, explicit)
    explicit = with_watched(state, host, explicit)
    blocks = state.get("consecutive_blocks", 0) if isinstance(state.get("consecutive_blocks"), int) else 0
    if event == "Stop" and blocks >= MAX_CONSECUTIVE_BLOCKS:
        state["consecutive_blocks"] = 0
        save_state(path, state)
        return 0

    # A watcher mid-check holds the lock; it will report what it finds, so a
    # hook that cannot get the lock quickly lets the agent stop.
    with state_lock(path, wait=LOCK_WAIT_SECONDS) as acquired:
        if not acquired:
            log("another pr-watch check is running; leaving it to report")
            return 0
        started = time.monotonic()
        prs = fetch_pull_requests(host, branch_target, explicit)
        if prs is None:
            return 0
        log(f"fetched {len(prs)} pull request(s) in {time.monotonic() - started:.1f}s")
        return report(event, harness, path, prs, blocks)


def report(event: str, harness: str, path: Path, prs: list[dict], blocks: int) -> int:
    state = load_state(path)  # Again, under the lock: the watcher may have updated it.
    message, notices = summarize(prs, state)
    if event == "SessionStart":
        if message:
            emit_session_context(harness, message)
        state["consecutive_blocks"] = 0
    elif message:
        emit_continue(harness, message)
        state["consecutive_blocks"] = blocks + 1
    else:
        state["consecutive_blocks"] = 0
        if notices:
            emit_notice(harness, " ".join(notices))
    save_state(path, state)
    return 0


def env_seconds(name: str, default: float) -> float:
    try:
        value = float(os.environ.get(name, default))
    except ValueError:
        return default
    return value if value > 0 else default


def rewake(path: Path, host: str, branch_target, explicit) -> int:
    """Claude Code's background watcher: exit 2 with the summary on stderr when something new arrives."""
    if os.environ.get("PR_WATCH_REWAKE") == "0":
        return 0
    if os.environ.get("CLAUDE_CODE_REMOTE", "").lower() == "true" and os.environ.get("PR_WATCH_REWAKE") != "1":
        return 0  # Cloud sessions can subscribe to pull request events instead.
    interval = env_seconds("PR_WATCH_REWAKE_INTERVAL", 120)
    end = time.monotonic() + env_seconds("PR_WATCH_REWAKE_SECONDS", 1500)
    # Each Stop starts a watcher; the newest one for a session wins.
    watcher = path.with_suffix(".watcher")
    token = f"{os.getpid()}-{time.time_ns()}"
    try:
        watcher.parent.mkdir(parents=True, exist_ok=True)
        watcher.write_text(token, encoding="utf-8")
    except OSError:
        return 0
    failures = 0
    while True:
        remaining = end - time.monotonic()
        if remaining <= 0:
            return 0
        time.sleep(min(interval, remaining))
        try:
            if watcher.read_text(encoding="utf-8") != token:
                return 0  # A newer watcher took over.
        except OSError:
            return 0
        with state_lock(path):
            prs = fetch_pull_requests(host, branch_target, with_watched(load_state(path), host, explicit))
            if prs is None:
                failures += 1
                if failures >= 3:
                    return 0
                continue
            failures = 0
            state = load_state(path)
            message, _ = summarize(prs, state)  # Reports a merge or close before giving up on it.
            save_state(path, state)
        if message:
            print(message, file=sys.stderr)
            return 2
        if not any(pr.get("state") == "OPEN" and not pr.get("merged") for pr in prs):
            return 0  # Nothing left to watch.


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except SystemExit:
        raise
    except Exception as error:  # The hook must never break the agent's stop.
        log(f"unexpected error: {error!r}")
        sys.exit(0)
